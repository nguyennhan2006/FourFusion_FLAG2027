def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def tables_A(src, name, out):
    """Listing A: the executed FLAG_08 code path (DirArchive or zip), meta lines of extract_external without the encoders."""
    z = open_archive(src)
    wavs, faces = [], {}
    for i in z.infolist():                                              # verbatim loop of extract_external
        if i.is_dir():
            continue
        r = _parse(i.filename)
        if r is None:
            continue
        if r[0] == "voices" and i.filename.lower().endswith(".wav"):
            wavs.append((i.filename,) + r[1:])
        elif r[0] == "faces" and i.filename.lower().endswith(".jpg"):
            faces.setdefault(r[1:], []).append(i.filename)
    log(f"A {name}: {len(wavs)} wav, {sum(map(len, faces.values()))} jpg in {len(faces)} videos, "
        f"{len({w[1] for w in wavs})} ids, langs {sorted({w[2] for w in wavs})}")
    durs = np.array([z.getinfo(f).file_size / 32000 for f, *_ in wavs], dtype=np.float32)   # sort key only (verbatim)
    pd.DataFrame(dict(path=[w[0] for w in wavs], spk=[w[1] for w in wavs], lang=[w[2] for w in wavs],
                      video=[w[3] for w in wavs], dur=durs)).to_csv(out / f"ext_{name}_voice_meta.csv", index=False)
    pick = []
    for key, fs in sorted(faces.items()):                               # verbatim face selection (8 evenly spaced frames)
        fs = sorted(fs)
        sel = np.unique(np.linspace(0, len(fs) - 1, min(8, len(fs))).round().astype(int))
        pick += [(fs[j],) + key for j in sel]
    pd.DataFrame(dict(path=[p[0] for p in pick], spk=[p[1] for p in pick], lang=[p[2] for p in pick],
                      video=[p[3] for p in pick])).to_csv(out / f"ext_{name}_face_meta.csv", index=False)
    write_speaker_meta(src, name, out)
    return len(wavs), len(pick)


