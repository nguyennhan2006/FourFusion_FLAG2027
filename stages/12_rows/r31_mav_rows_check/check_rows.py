def first_diff(a, b):
    """First differing row of two csv files (row order diagnostics)."""
    A, B = pd.read_csv(a, dtype=str), pd.read_csv(b, dtype=str)
    n = min(len(A), len(B))
    neq = np.where((A.iloc[:n].values != B.iloc[:n].values).any(1))[0]
    return dict(rows=[len(A), len(B)], first_diff_row=int(neq[0]) if len(neq) else (None if len(A) == len(B) else n),
                same_row_set=bool(set(map(tuple, A.values)) == set(map(tuple, B.values))))


