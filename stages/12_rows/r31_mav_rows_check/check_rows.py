def _parse(member):
    """faces|voices/<id>/<lang>/<video>/<file> (optionally under a version folder) -> (kind, id, lang, video)."""
    p = member.split("/")
    for kind in ("voices", "faces"):
        if kind in p:
            k = p.index(kind)
            if len(p) >= k + 5:
                return kind, p[k + 1], p[k + 2].lower(), p[k + 3]
    return None

